package io.micronaut.security.token.jwt.roles

import io.micronaut.context.annotation.Requires
import io.micronaut.http.HttpRequest
import io.micronaut.http.MediaType
import io.micronaut.http.annotation.Controller
import io.micronaut.http.annotation.Get
import io.micronaut.http.annotation.Produces
import io.micronaut.security.annotation.Secured
import io.micronaut.security.testutils.EmbeddedServerSpecification
import io.micronaut.security.token.jwt.generator.JwtTokenGenerator

class RolesSeparatorRegexSpec extends EmbeddedServerSpecification {

    @Override
    String getSpecName() {
        'RolesSeparatorRegexSpec'
    }

    @Override
    Map<String, Object> getConfiguration() {
        super.configuration + [
            'micronaut.security.token.roles-name' : 'scope',
            'micronaut.security.token.roles-separator' : '.',
            'micronaut.security.token.jwt.signatures.secret.generator.secret': 'pleaseChangeThisSecretForANewOne',
        ]
    }

    void "it is possible to specify the claim name which stores the roles and split them using a separator, the separator is a literal pattern, not a regex"() {
        given: '''A JWT that may be generated outside of Micronaut.
This token is generated with the secret-signature configuration so the signature can be easily validated in the test.
But in real life it may be a token generated by a third-party authorization server. Thus, we have no control over the claims.
        '''
        JwtTokenGenerator tokenGenerator = applicationContext.getBean(JwtTokenGenerator)
        String jwt = tokenGenerator.generateToken([sub: 'john', scope: 'read.write']).get()

        when:
        client.exchange(HttpRequest.GET('/nightwatch').bearerAuth(jwt))

        then:
        noExceptionThrown()

        when:
        client.exchange(HttpRequest.GET('/kingguard').bearerAuth(jwt))

        then:
        noExceptionThrown()
    }

    @Requires(property = 'spec.name', value = 'RolesSeparatorRegexSpec')
    @Controller
    static class NightWatchController {
        @Produces(MediaType.TEXT_PLAIN)
        @Secured("read")
        @Get("/nightwatch")
        String nightwatch() {
            'You are a crow'
        }

        @Produces(MediaType.TEXT_PLAIN)
        @Secured(["read", "write"])
        @Get("/kingguard")
        String kingguard() {
            'You are a white cloak'
        }
    }
}

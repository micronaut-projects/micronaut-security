package io.micronaut.security.csp.filters;

import io.micronaut.context.annotation.Requires;
import io.micronaut.context.event.ApplicationEventListener;
import io.micronaut.context.event.StartupEvent;
import io.micronaut.core.annotation.Internal;
import io.micronaut.http.HttpHeaders;
import io.micronaut.security.csp.ContentSecurityPolicyGenerator;
import io.micronaut.security.csp.conf.ContentSecurityPolicyConfiguration;
import io.micronaut.security.csp.conf.ContentSecurityPolicyDirectiveConfigurations;
import jakarta.inject.Singleton;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Logs once at startup which CSP header the module writes and where, because adding the module
 * applies a deny-by-default policy to every matching response. It runs only when the header
 * populator exists, so it never claims a header that is not written.
 */
@Requires(beans = ContentSecurityPolicyResponseHeaderPopulator.class)
@Singleton
@Internal
final class ContentSecurityPolicyStartupLogger implements ApplicationEventListener<StartupEvent> {
    private static final Logger LOG = LoggerFactory.getLogger(ContentSecurityPolicyStartupLogger.class);
    private final ContentSecurityPolicyConfiguration cspConfiguration;
    private final ContentSecurityPolicyFilterConfiguration filterConfiguration;
    private final ContentSecurityPolicyDirectiveConfigurations directiveConfigurations;
    private final String generatorName;

    /**
     * Creates the startup logger.
     *
     * <p>The generator is injected so that it is created at startup: invalid policy configuration
     * then fails application startup instead of every response.</p>
     *
     * @param cspConfiguration the root CSP configuration
     * @param filterConfiguration the configuration of the requests that receive the header
     * @param cspGenerator the policy generator, created eagerly to validate its configuration
     * @param directiveConfigurations the directive configurations, which tell whether violations are reported
     */
    ContentSecurityPolicyStartupLogger(ContentSecurityPolicyConfiguration cspConfiguration,
                                       ContentSecurityPolicyFilterConfiguration filterConfiguration,
                                       ContentSecurityPolicyGenerator cspGenerator,
                                       ContentSecurityPolicyDirectiveConfigurations directiveConfigurations) {
        this.cspConfiguration = cspConfiguration;
        this.filterConfiguration = filterConfiguration;
        this.directiveConfigurations = directiveConfigurations;
        this.generatorName = cspGenerator.getClass().getName();
    }

    @Override
    public void onApplicationEvent(StartupEvent event) {
        if (cspConfiguration.isReportOnly()) {
            if (directiveConfigurations.getReportTo().isEnabled() || directiveConfigurations.getReportUri().isEnabled()) {
                LOG.info("Writing the {} header generated by {} on requests matching {}; violations are not blocked, and browsers send them "
                    + "to the configured report-to group or report-uri endpoints. Remove micronaut.security.csp.report-only to enforce the policy.",
                    HttpHeaders.CONTENT_SECURITY_POLICY_REPORT_ONLY, generatorName, filterConfiguration.getPattern());
            } else {
                LOG.info("Writing the {} header generated by {} on requests matching {}; violations are not blocked and only appear "
                    + "in the browser console, because neither report-to nor report-uri is enabled. "
                    + "Remove micronaut.security.csp.report-only to enforce the policy.",
                    HttpHeaders.CONTENT_SECURITY_POLICY_REPORT_ONLY, generatorName, filterConfiguration.getPattern());
            }
        } else {
            LOG.info("Enforcing the {} header generated by {} on requests matching {}. Pages that load scripts, styles or images "
                + "the policy does not allow will break. Set micronaut.security.csp.report-only=true to evaluate the policy first.",
                HttpHeaders.CONTENT_SECURITY_POLICY, generatorName, filterConfiguration.getPattern());
        }
    }
}
